-- Modelo de dados do AgroCusto (Oracle 12c ou superior)
-- Executado automaticamente pelo sistema na primeira conexão.

CREATE TABLE TB_TALHAO (
    ID_TALHAO        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NM_TALHAO        VARCHAR2(50)  NOT NULL,
    DS_CULTURA       VARCHAR2(30)  NOT NULL,
    VL_AREA_HA       NUMBER(10,2)  NOT NULL CHECK (VL_AREA_HA > 0),
    VL_PRODUTIVIDADE NUMBER(10,2)  NOT NULL CHECK (VL_PRODUTIVIDADE > 0),
    VL_PRECO_SACA    NUMBER(10,2)  NOT NULL CHECK (VL_PRECO_SACA > 0),
    DT_PLANTIO       DATE          NOT NULL
);

CREATE TABLE TB_CUSTO (
    ID_CUSTO     NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_TALHAO    NUMBER        NOT NULL,
    DS_CATEGORIA VARCHAR2(30)  NOT NULL,
    DS_CUSTO     VARCHAR2(100) NOT NULL,
    VL_CUSTO     NUMBER(12,2)  NOT NULL CHECK (VL_CUSTO > 0),
    DT_CUSTO     DATE          NOT NULL,
    CONSTRAINT FK_CUSTO_TALHAO FOREIGN KEY (ID_TALHAO)
        REFERENCES TB_TALHAO (ID_TALHAO) ON DELETE CASCADE
);
